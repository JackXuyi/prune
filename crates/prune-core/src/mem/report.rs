//! 内存报告聚合与 CSV 导出（F20，docs/f20-memory-report-plan.md）。
//!
//! 竞品依据：Vitals 1.11 的 Memory Report（分时峰值 + 每进程 + CSV）。
//! 边界纪律：导出是**读历史**不是诊断——纯观测数值，没有任何结论字段
//! （泄漏嫌疑归 mem_leaks，swap 判断归 M3）。
//!
//! 两条设计决策（f20 §4.1）：
//! 1. **聚合维度 = (name, family)**，不按 pid 分行——用户关心「Safari 这 7 天」
//!    不是「pid 626 那段」；pid 只作为末次锚点附带；
//! 2. **峰值取原始样本最大值**，不做降采样后再取峰（会丢尖峰——报告的价值恰在尖峰）。
//!
//! **空窗（gaps）必须进报告**：Prune 没跑的时段不能让读者误以为「当时很干净」。
//! 判据：相邻采样间隔 > 3 × 采样周期中位数（自适应节奏，不硬编码周期）。

use crate::db::MemReportRow;
use serde::{Deserialize, Serialize};

/// 每进程一行（峰值 RSS 降序输出）。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ProcMemReport {
    pub name: String,
    pub family: String,
    /// 末次观测 pid（进程会重生，pid 只是锚点）
    pub pid: i32,
    /// 原始样本峰值（字节）
    pub peak_rss: u64,
    /// 峰值出现的采样时刻
    pub peak_ts: i64,
    pub peak_swapped: Option<u64>,
    /// 全窗口均值（字节，整数平均）
    pub avg_rss: u64,
    /// 样本数；0 样本的进程不进表
    pub samples: u32,
}

/// 一次报告的完整产出。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MemReport {
    pub from_ts: i64,
    pub to_ts: i64,
    /// 每进程一行，峰值 RSS 降序
    pub procs: Vec<ProcMemReport>,
    /// 采样空窗 [(start, end)]：Prune 没跑的时段，随 CSV 尾注输出
    pub gaps: Vec<(i64, i64)>,
}

/// 主入口：原始行 → 聚合。纯函数。
///
/// `rows` 需已按 ts 升序（`mem_report_rows` 的 ORDER BY 保证）；空输入返回
/// 全空报告（调用方决定「暂无数据」的呈现，这里不撒「0 字节」的谎）。
pub fn aggregate(rows: &[MemReportRow]) -> MemReport {
    let mut report = MemReport {
        from_ts: rows.first().map(|r| r.ts).unwrap_or(0),
        to_ts: rows.last().map(|r| r.ts).unwrap_or(0),
        procs: Vec::new(),
        gaps: Vec::new(),
    };
    if rows.is_empty() {
        return report;
    }

    /// 聚合中间槽（avg_sum 是中间量，不进序列化形状）
    struct Agg {
        pid: i32,
        peak_rss: u64,
        peak_ts: i64,
        peak_swapped: Option<u64>,
        sum: u64,
        samples: u32,
    }

    // (name, family) → 聚合槽
    let mut slots: std::collections::HashMap<(String, String), Agg> =
        std::collections::HashMap::new();
    for r in rows {
        let key = (r.name.clone(), r.family.clone());
        match slots.get_mut(&key) {
            Some(s) => {
                s.samples += 1;
                s.sum += r.rss;
                if r.rss > s.peak_rss {
                    s.peak_rss = r.rss;
                    s.peak_ts = r.ts;
                }
                s.peak_swapped = match (s.peak_swapped, r.swapped) {
                    (Some(a), Some(b)) => Some(a.max(b)),
                    (Some(a), None) => Some(a),
                    (None, Some(b)) => Some(b),
                    (None, None) => None,
                };
                s.pid = r.pid; // 末次锚点
            }
            None => {
                slots.insert(
                    key,
                    Agg {
                        pid: r.pid,
                        peak_rss: r.rss,
                        peak_ts: r.ts,
                        peak_swapped: r.swapped,
                        sum: r.rss,
                        samples: 1,
                    },
                );
            }
        }
    }
    report.procs = slots
        .into_iter()
        .map(|((name, family), s)| ProcMemReport {
            name,
            family,
            pid: s.pid,
            peak_rss: s.peak_rss,
            peak_ts: s.peak_ts,
            peak_swapped: s.peak_swapped,
            avg_rss: s.sum / s.samples.max(1) as u64,
            samples: s.samples,
        })
        .collect();
    report.procs.sort_by_key(|p| std::cmp::Reverse(p.peak_rss));

    report.gaps = detect_gaps(rows);
    report
}

/// 采样空窗检测：相邻采样间隔 > 3 × 周期中位数记一段。
/// 周期取**中位数**而不是均值——均值会被一次长停机拉爆，中位数稳。
fn detect_gaps(rows: &[MemReportRow]) -> Vec<(i64, i64)> {
    let ts: Vec<i64> = {
        let mut v: Vec<i64> = rows.iter().map(|r| r.ts).collect();
        v.dedup();
        v.sort_unstable();
        v
    };
    if ts.len() < 3 {
        return Vec::new();
    }
    let mut intervals: Vec<i64> = ts.windows(2).map(|w| w[1] - w[0]).collect();
    intervals.sort_unstable();
    let median = intervals[intervals.len() / 2].max(1);
    let threshold = median * 3;
    let mut gaps = Vec::new();
    for w in ts.windows(2) {
        if w[1] - w[0] > threshold {
            gaps.push((w[0], w[1]));
        }
    }
    gaps
}

/// CSV 渲染。机器可读优先：单位进列名，不合并单元格；含逗号/引号的字段
/// 走标准 quoting。首行注释写生成信息（Excel/Numbers 对 `#` 开头行不建列）。
pub fn to_csv(report: &MemReport, generated_at: i64, version: &str) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "# generated by Prune v{version} at {generated_at}\n"
    ));
    out.push_str("section,ts,name,family,pid,rss_mb,swapped_mb,samples,note\n");
    out.push_str(&format!(
        "summary,{},,,,,,,\"window start\"\n",
        report.from_ts
    ));
    out.push_str(&format!(
        "summary,{},,,,,,,\"window end\"\n",
        report.to_ts
    ));
    for (start, end) in &report.gaps {
        out.push_str(&format!(
            "gap,{start},,,,,,,\"Prune 未运行 {start} -> {end}，该时段无观测\"\n"
        ));
    }
    for p in &report.procs {
        out.push_str(&format!(
            "{},{},{},{},{},{:.1},{},{},\n",
            "proc",
            p.peak_ts,
            csv_escape(&p.name),
            csv_escape(&p.family),
            p.pid,
            p.peak_rss as f64 / 1_048_576.0,
            p.peak_swapped
                .map(|s| format!("{:.1}", s as f64 / 1_048_576.0))
                .unwrap_or_default(),
            p.samples,
        ));
    }
    out
}

/// CSV 字段转义：含逗号 / 引号 / 换行的字段加引号，内部引号翻倍。
pub fn csv_escape(s: &str) -> String {
    if s.contains(',') || s.contains('"') || s.contains('\n') {
        format!("\"{}\"", s.replace('"', "\"\""))
    } else {
        s.to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn row(ts: i64, pid: i32, name: &str, family: &str, rss: u64) -> MemReportRow {
        MemReportRow {
            ts,
            pid,
            name: name.into(),
            family: family.into(),
            rss,
            swapped: None,
        }
    }

    #[test]
    fn aggregate_merges_by_name_family_not_pid() {
        // 同一进程重生（pid 100 → 200）：报告里是一行，pid 取末次锚点
        let rows = vec![
            row(100, 100, "Safari", "app", 1_000_000),
            row(300, 200, "Safari", "app", 3_000_000), // 峰值
            row(500, 200, "Safari", "app", 2_000_000),
            row(100, 300, "node", "project:prune", 400_000),
        ];
        let r = aggregate(&rows);
        assert_eq!(r.procs.len(), 2);
        assert_eq!(r.procs[0].name, "Safari"); // 峰值降序
        assert_eq!(r.procs[0].peak_rss, 3_000_000);
        assert_eq!(r.procs[0].peak_ts, 300);
        assert_eq!(r.procs[0].pid, 200, "末次锚点");
        assert_eq!(r.procs[0].samples, 3);
        assert_eq!(r.procs[0].avg_rss, 2_000_000);
        assert_eq!(r.procs[1].name, "node");
    }

    #[test]
    fn aggregate_empty_is_empty_not_zero() {
        let r = aggregate(&[]);
        assert!(r.procs.is_empty());
        assert_eq!(r.from_ts, 0);
    }

    #[test]
    fn gaps_detected_by_median_times_three() {
        // 周期 100s 稳定采样，中间停机 1000s（> 3×100）→ 一段空窗
        let mut rows = Vec::new();
        for i in 0..10u64 {
            rows.push(row(1000 + (i * 100) as i64, 1, "a", "app", 1));
        }
        for i in 0..10u64 {
            rows.push(row(5000 + (i * 100) as i64, 1, "a", "app", 1));
        }
        let r = aggregate(&rows);
        assert_eq!(r.gaps.len(), 1);
        assert_eq!(r.gaps[0], (1900, 5000));
        // 短停机（2× 周期）不算空窗
        let mut rows2 = Vec::new();
        for i in 0..6u64 {
            rows2.push(row(1000 + (i * 100) as i64, 1, "a", "app", 1));
        }
        rows2.push(row(1300, 1, "a", "app", 1));
        rows2.push(row(1400, 1, "a", "app", 1));
        assert!(aggregate(&rows2).gaps.is_empty());
    }

    #[test]
    fn csv_escapes_commas_and_quotes() {
        assert_eq!(csv_escape("plain"), "plain");
        assert_eq!(csv_escape("a,b"), "\"a,b\"");
        assert_eq!(csv_escape("say \"hi\""), "\"say \"\"hi\"\"\"");
        let rows = vec![row(100, 1, "app, beta", "fam", 1_048_576)];
        let csv = to_csv(&aggregate(&rows), 999, "0.0.1");
        assert!(csv.contains("\"app, beta\""), "{csv}");
        assert!(csv.contains("rss_mb"), "单位进列名：{csv}");
        assert!(csv.starts_with("# generated by Prune v0.0.1 at 999"));
        // 1 MiB → 1.0 MB 列
        assert!(csv.contains("1.0"));
    }

    #[test]
    fn peak_swapped_takes_max_across_samples() {
        let mut rows = vec![
            MemReportRow { ts: 1, pid: 1, name: "n".into(), family: "f".into(), rss: 1, swapped: Some(10) },
            MemReportRow { ts: 2, pid: 1, name: "n".into(), family: "f".into(), rss: 2, swapped: Some(30) },
            MemReportRow { ts: 3, pid: 1, name: "n".into(), family: "f".into(), rss: 3, swapped: None },
        ];
        rows.reverse(); // 乱序输入也要取对
        let r = aggregate(&rows);
        assert_eq!(r.procs[0].peak_swapped, Some(30));
    }
}
